    def test_namespace(self) -> None:
        repo = Repo(self)
        doc, _ = repo.build(version="1.2")
        prefix = "https://vilnaos.com/spdx/vilna-1.2-"
        namespace = doc["documentNamespace"]
        self.assertTrue(namespace.startswith(prefix))
        self.assertRegex(namespace[len(prefix) :], r"^[0-9a-f]{64}$")
        later, _ = repo.build(version="1.2", created="2027-01-01T00:00:00Z")
        self.assertEqual(later["documentNamespace"], namespace)  # created is not in the hash
        self.assertNotEqual(later["creationInfo"]["created"], doc["creationInfo"]["created"])
