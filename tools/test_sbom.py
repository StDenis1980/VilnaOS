def add_sdist(lock: str, sha: str) -> str:
    """The lock text with an sdist for ``baz`` (which has only wheels)."""
    wheels = 'wheels = [\n    { url = "https://files.example/baz-2.0-py3-none-any.whl"'
    sdist = f'sdist = {{ url = "https://files.example/baz-2.0.tar.gz", hash = "sha256:{sha}" }}\n'
    assert wheels in lock
    return lock.replace(wheels, sdist + wheels)


def write(root: Path, files: dict[str, str]) -> list[str]:
    """Write ``files`` under ``root``; return their sorted paths (like ``git ls-files``)."""
    for rel, text in files.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return sorted(files)


