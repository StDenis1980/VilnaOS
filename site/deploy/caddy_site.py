"""Write the Caddy site block for the spare host of vilnaos.com (ADR 0032).

    python3 site/deploy/caddy_site.py [site/public] > vilnaos.com.caddy

statichost reads site/public/_headers and _redirects itself; Caddy does
not, so this turns both into Caddy directives. The spare host then sends
the same security headers, the same /en/ redirect and the same 404 page
per language as the main one. The certificate comes from lego
(site/deploy/cert.sh), not from Caddy, so it exists before a failover.

Stdlib only. Run by site/deploy/update.sh on the VPS, and by CI through
tools/test_site_dns.py, so a header added to _headers cannot be missed.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
PUBLIC = ROOT / "site" / "public"
WEBROOT = "/var/www/vilnaos.com/current"
CERT = "/etc/caddy/certs/vilnaos.com.crt"
KEY = "/etc/caddy/certs/vilnaos.com.key"
ZONE = "vilnaos.com"


def headers(public: Path) -> list[tuple[str, str]]:
    """Headers for every path ("*") from _headers, in order."""
    out: list[tuple[str, str]] = []
    current = None
    for line in (public / "_headers").read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if not line[0].isspace():
            current = line.strip()
            continue
        if current != "*":
            raise ValueError(f"_headers: only '*' is supported here, not {current!r}")
        name, _, value = line.strip().partition(":")
        out.append((name.strip(), value.strip()))
    return out


def redirects(public: Path) -> tuple[list[tuple[str, str]], list[str]]:
    """(301 prefix moves, languages with their own 404 page) from _redirects."""
    moves: list[tuple[str, str]] = []
    langs: list[str] = []
    for line in (public / "_redirects").read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if not parts or parts[0].startswith("#"):
            continue
        src, dst, code = parts
        if code == "301" and src.endswith("/*") and dst.endswith("/:splat"):
            moves.append((src[:-1], dst[: -len(":splat")]))
        elif code == "404" and (m := re.fullmatch(r"/([a-z]{2})/\*", src)):
            langs.append(m.group(1))
        elif code == "404" and src == "/*":
            continue
        else:
            raise ValueError(f"_redirects: rule not supported on the spare host: {line!r}")
    return moves, langs


def quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(public: Path = PUBLIC) -> str:
    moves, langs = redirects(public)
    lines = [
        "# SPDX-License-Identifier: GPL-3.0-or-later",
        "# Generated by site/deploy/caddy_site.py from site/public/_headers and",
        "# _redirects; site/deploy/update.sh rewrites it. Do not edit here.",
        f"{ZONE} {{",
        f"\ttls {CERT} {KEY}",
        f"\troot * {WEBROOT}",
        "\theader {",
        "\t\t-Server",
    ]
    lines += [f"\t\t{name} {quote(value)}" for name, value in headers(public)]
    lines.append("\t}")
    for i, (src, dst) in enumerate(moves):
        lines += [
            f"\t@move{i} path_regexp move{i} ^{re.escape(src)}(.*)$",
            f"\tredir @move{i} {dst}{{re.move{i}.1}} 301",
        ]
    lines += [
        "\tfile_server",
        # Caddy 2.6 in Debian 13 has no status filter on handle_errors; a
        # static site only fails with 404 (403 for a hidden file), and the
        # status code stays the error's own.
        "\thandle_errors {",
    ]
    if langs:
        alt = "|".join(langs)
        lines += [
            f"\t\t@lang path_regexp lang ^/({alt})/",
            "\t\trewrite @lang /{re.lang.1}/404.html",
        ]
    lines += [
        "\t\t@other not path_regexp ^/(" + "|".join(langs) + ")/" if langs else "",
        "\t\trewrite @other /404.html" if langs else "\t\trewrite * /404.html",
        "\t\tfile_server",
        "\t}",
        "}",
        "",
        f"www.{ZONE} {{",
        f"\ttls {CERT} {KEY}",
        "\theader -Server",
        f"\tredir https://{ZONE}{{uri}} 301",
        "}",
        "",
    ]
    return "\n".join(line for line in lines if line != "") + "\n"


def main(argv: list[str]) -> int:
    public = Path(argv[1]) if len(argv) > 1 else PUBLIC
    try:
        sys.stdout.write(render(public))
    except (OSError, ValueError) as e:
        print(e, file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
